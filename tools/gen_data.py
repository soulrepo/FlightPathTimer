"""Generate FlightPathData.lua from TaxiNodes/TaxiPath/TaxiPathNode.dbc.

usage: gen_data.py <dir with the .dbc files> <output .lua>
"""
import math, os, struct, sys
D=os.path.join(sys.argv[1], "")
def load(n):
    d=open(D+n+".dbc","rb").read()
    _,rec,fld,rs,ss=struct.unpack("<4s4I",d[:20])
    recs=[d[20+i*rs:20+(i+1)*rs] for i in range(rec)]
    strs=d[20+rec*rs:]
    return recs,strs
def s(strs,o): return strs[o:strs.index(b"\0",o)].decode("utf8","replace")
nr,ns=load("TaxiNodes")
nodes={}
for r in nr:
    v=struct.unpack("<IIfff9I2I",r)
    nodes[v[0]]=dict(id=v[0],map=v[1],x=v[2],y=v[3],z=v[4],name=s(ns,v[5]))
pr,_=load("TaxiPath")
paths={}
for r in pr:
    i,a,b,c=struct.unpack("<4I",r); paths[i]=(a,b,c)
pnr,_=load("TaxiPathNode")
pts={}
for r in pnr:
    i,pid,idx,m,x,y,z,fl,delay=struct.unpack("<IIIIfffII",r)
    pts.setdefault(pid,[]).append((idx,m,x,y,z,fl,delay))
SPEED = 32.0          # yards/second, taxi flight speed
OVERHEAD = 1.006      # measured: recorded times run ~0.6% over length/32
def leg_seconds(pid):
    p = sorted(pts.get(pid, []))
    L = 0.0
    for a, b in zip(p, p[1:]):
        if a[1] != b[1] or a[5] & 1 or b[5] & 1:
            continue
        L += math.dist(a[2:5], b[2:5])
    return L / SPEED * OVERHEAD
skip = ("Transport", "Boat", "Zeppelin", "Generic")
names = {}
for i, n in sorted(nodes.items()):
    if n['name'] and not n['name'].startswith(skip):
        names.setdefault(n['name'], []).append(i)
valid = {i for ids in names.values() for i in ids}
legs = {}
for pid, (a, b, c) in sorted(paths.items()):
    if a in valid and b in valid and pid in pts and not any(q[6] for q in pts[pid]):
        legs["%d-%d" % (a, b)] = round(leg_seconds(pid), 1)
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ["-- Generated by tools/gen_data.py from the client's TaxiNodes, TaxiPath and TaxiPathNode tables.",
       "-- pos is each flight point's world x, y. Leg times are path length / 32 yards per second.", "-- Do not edit by hand.", "",
       "FlightPathTimerData = {", "    nodes = {"]
for n, ids in sorted(names.items()):
    out.append("        [%s] = { %s }," % (q(n), ", ".join(map(str, ids))))
out += ["    },", "    pos = {"]
for i in sorted(valid):
    out.append("        [%d] = { %.1f, %.1f }," % (i, nodes[i]['x'], nodes[i]['y']))
out += ["    },", "    legs = {"]
for k, v in sorted(legs.items(), key=lambda kv: tuple(map(int, kv[0].split('-')))):
    out.append('        ["%s"] = %s,' % (k, v))
out += ["    },", "}", ""]
open(sys.argv[2], "w").write("\n".join(out))
print(len(names), "nodes,", len(legs), "legs")
